# Object-level metadata that is structure, not a setting override.
OBJECT_META_NOT_SETTINGS = {"name"}

_OBJECT_RE = re.compile(
    r'<object id="(?P<id>\d+)"(?P<attrs>[^>]*)>(?P<body>.*?)</object>',
    re.S)
_OBJ_META_RE = re.compile(
    r'<metadata type="object" key="([^"]+)" value="([^"]*)"/>')


def object_entries(model_config_xml):
    """{object id: {"name", "instances", "overrides": {key: value}}}.

    overrides holds every object-level metadata line except the name -
    including "extruder", which the session treats like Bambu's
    object-level extruder line.
    """
    result = {}
    for m in _OBJECT_RE.finditer(model_config_xml):
        oid = m.group("id")
        inst = re.search(r'instances_count="(\d+)"', m.group("attrs"))
        head = m.group("body").split("<volume", 1)[0]
        meta = dict(_OBJ_META_RE.findall(head))
        name = _unescape(meta.pop("name", "")) or f"object {oid}"
        result[oid] = {
            "name": name,
            "instances": int(inst.group(1)) if inst else 1,
            "overrides": {k: _unescape(v) for k, v in meta.items()},
        }
    return result


def _escape(value):
    return (str(value).replace("&", "&amp;").replace("<", "&lt;")
            .replace('"', "&quot;"))


def _unescape(value):
    return (value.replace("&quot;", '"').replace("&lt;", "<")
            .replace("&gt;", ">").replace("&amp;", "&"))


def set_object_metadata(model_config_xml, objectid, key, value):
    """Set, change or (value None) remove one object-level metadata
    line, formatted exactly as PrusaSlicer writes them: after the name
    line, before the first <volume>. Returns the new XML text; raises
    KeyError when the object has no block."""
    for m in _OBJECT_RE.finditer(model_config_xml):
        if m.group("id") != objectid:
            continue
        body = m.group("body")
        head, sep, tail = body.partition("<volume")
        line_re = re.compile(
            rf'\n?[ \t]*<metadata type="object" key="{re.escape(key)}" '
            rf'value="[^"]*"/>')
        if value is None:
            new_head = line_re.sub("", head)
        elif line_re.search(head):
            new_head = line_re.sub(
                lambda mm: mm.group(0).split("<metadata", 1)[0]
                + f'<metadata type="object" key="{key}" '
                f'value="{_escape(value)}"/>', head, count=1)
        else:
            line = (f'\n  <metadata type="object" key="{key}" '
                    f'value="{_escape(value)}"/>')
            name_m = re.search(
                r'<metadata type="object" key="name" value="[^"]*"/>',
                head)
            if name_m:
                new_head = head[:name_m.end()] + line + head[name_m.end():]
            else:
                new_head = line + head
        start = m.start("body")
        return (model_config_xml[:start] + new_head + sep + tail
                + model_config_xml[m.end("body"):])
    raise KeyError(objectid)


def rename_objects_to_basenames(model_config_xml):
    """The CLI names objects by the model file's full path; the GUI
    uses the bare file name. Bring CLI-made projects in line."""
    def fix(m):
        value = _unescape(m.group(2))
        base = value.replace("\\", "/").rsplit("/", 1)[-1]
        return m.group(1) + _escape(base) + m.group(3)
    return re.sub(r'(<metadata type="(?:object|volume)" key="name" value=")'
                  r'([^"]*)(")', fix, model_config_xml)
