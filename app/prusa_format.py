"""prusa_format.py - the PrusaSlicer project format, as text.

A PrusaSlicer project 3MF (probed 2026-09-02 on real map-tile files
saved by 2.9.4 and on CLI exports from 2.9.6, docs\\log.md) is the
same core 3MF as Bambu's - 3D/3dmodel.model with build items and
transforms in the row-vector convention - but keeps its settings as
plain INI-style text instead of JSON, and its meshes inline:

- Metadata/Slic3r_PE.config: one "; key = value" line per setting,
  every scope merged into one flat namespace (print, filament and
  printer keys side by side), preceded by a "; generated by
  PrusaSlicer 2.9.4 on ..." header line. Per-extruder settings are
  comma-separated ("temperature = 225,225"), per-extruder texts are
  semicolon-separated ("filament_type = PLA;PLA"), and per-extruder
  texts that may hold anything are quoted and semicolon-separated
  ('filament_settings_id = "A";"B"'). Which keys are per-extruder is
  not visible in a single-extruder file, so the list below was read
  off a genuine five-tool XL project and is pinned by tests.
- Metadata/Slic3r_PE_model.config: an XML <config> with one <object
  id="N" instances_count="K"> per object, whose object-level
  <metadata type="object" key=... value=.../> lines carry the name,
  the extruder, and every per-object setting override; the <volume>
  children describe the mesh parts.
- Meshes live inline in 3D/3dmodel.model (no 3D/Objects/*.model
  files), which geometry.py already reads.

Everything here is pure text in, text out - no writing to disk.
"""

