# Per-extruder texts, semicolon-separated, unquoted.
PER_EXTRUDER_SEMI = frozenset("""
custom_parameters_filament extruder_colour filament_colour
filament_notes filament_type filament_vendor
""".split())

# Per-extruder texts, each value in double quotes, semicolon-separated.
PER_EXTRUDER_QUOTED = frozenset("""
end_filament_gcode filament_ramming_parameters filament_settings_id
start_filament_gcode
""".split())

PER_EXTRUDER_KEYS = PER_EXTRUDER_COMMA | PER_EXTRUDER_SEMI \
    | PER_EXTRUDER_QUOTED

_LINE_RE = re.compile(r"^; ([A-Za-z0-9_]+) = (.*)$")


# ------------------------------------------------------ the config


def split_value(key, raw):
    """A raw config value -> str, or a list of str for per-extruder
    keys (one entry per extruder, quotes stripped for quoted keys)."""
    if key in PER_EXTRUDER_QUOTED:
        return _split_quoted(raw)
    if key in PER_EXTRUDER_SEMI:
        return raw.split(";") if raw != "" else [""]
    if key in PER_EXTRUDER_COMMA:
        return raw.split(",")
    return raw


def join_value(key, value):
    """The inverse of split_value, for writing the file back."""
    if not isinstance(value, list):
        return str(value)
    if key in PER_EXTRUDER_QUOTED:
        return ";".join('"' + _quote(v) + '"' for v in value)
    if key in PER_EXTRUDER_SEMI:
        return ";".join(str(v) for v in value)
    return ",".join(str(v) for v in value)


def _quote(text):
    return str(text).replace("\\", "\\\\").replace('"', '\\"')


def _split_quoted(raw):
    """'"A";"B"' -> ["A", "B"], honouring backslash escapes."""
    values, current, i, inside = [], [], 0, False
    if raw.strip() == "":
        return [""]
    while i < len(raw):
        ch = raw[i]
        if inside:
            if ch == "\\" and i + 1 < len(raw):
                current.append(raw[i + 1])
                i += 2
                continue
            if ch == '"':
                inside = False
                values.append("".join(current))
                current = []
            else:
                current.append(ch)
        elif ch == '"':
            inside = True
        i += 1
    if not values:
        # Unquoted after all (older files): plain semicolon split.
        return raw.split(";")
    return values


def parse_config(text):
    """Slic3r_PE.config text -> (header lines, {key: value}).

    Key order is the file's own and is kept for writing back. Lines
    that are not "; key = value" (the header, blanks) are kept as the
    header so the file round-trips byte-for-byte when nothing changed.
    """
    header, settings = [], {}
    for line in text.splitlines():
        m = _LINE_RE.match(line)
        if m and not settings and line.startswith("; generated"):
            header.append(line)
            continue
        if m:
            settings[m.group(1)] = split_value(m.group(1), m.group(2))
        elif not settings:
            header.append(line)
    return header, settings


def serialise_config(header, settings):
    """(header lines, {key: value}) -> Slic3r_PE.config text."""
    lines = list(header)
    if lines and lines[-1].strip() != "":
        lines.append("")
    for key, value in settings.items():
        lines.append(f"; {key} = {join_value(key, value)}")
    return "\n".join(lines) + "\n"


def generator_line(header):
    """The "PrusaSlicer 2.9.4" part of the header, or ""."""
    for line in header:
        m = re.search(r"(PrusaSlicer \d[^\s]*)", line)
        if m:
            return m.group(1)
    return ""


def bed_size(settings):
    """(width, depth) from bed_shape "0x0,250x0,250x220,0x220"."""
    raw = settings.get("bed_shape")
    if not isinstance(raw, str) or not raw:
        return None
    try:
        xs, ys = zip(*(map(float, c.split("x")) for c in raw.split(",")))
        return max(xs), max(ys)
    except (ValueError, TypeError):
        return None


