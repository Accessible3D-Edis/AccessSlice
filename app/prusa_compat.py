"""prusa_compat.py - which PrusaSlicer versions are verified.

Same policy as compat.py: actual breakage always fails loudly through
the structural checks; an unverified version is a spoken caution,
never a refusal.

2.9 verified 2026-09-02: real 2.9.4-saved projects (multi-colour map
tiles) read correctly; a Core One project assembled from 2.9.6's own
presets sliced headless (rc 0, binary G-code parsed). When a new
series is hand-verified, add it here and record the evidence in
docs\\log.md.
"""

import re

VERIFIED_SERIES = ("2.9",)
VERIFIED_TEXT = "PrusaSlicer 2.9"


def series(version_or_app):
    """The "major.minor" series of a version string, or "".

    Accepts the config header form ("PrusaSlicer 2.9.4", or the whole
    "; generated by PrusaSlicer 2.9.4 on ..." line), the CLI banner
    ("PrusaSlicer-2.9.6 based on Slic3r") and a bare "2.9.6".
    """
    text = (version_or_app or "").strip()
    m = re.search(r"PrusaSlicer[ -]+(\d+)\.(\d+)", text)
    if m:
        return f"{int(m.group(1))}.{int(m.group(2))}"
    parts = text.split(".")
    if len(parts) >= 2 and parts[0].isdigit() and parts[1].isdigit():
        return f"{int(parts[0])}.{int(parts[1])}"
    return ""


def unverified_note(version_or_app, what):
    """A plain-language caution outside the verified series, else None
    (unparseable stays quiet - the structural checks still guard)."""
    found = series(version_or_app)
    if not found or found in VERIFIED_SERIES:
        return None
    return (f"{what} comes from PrusaSlicer version {found}, which "
            f"AccessSlice has not been verified against yet (verified: "
            f"{VERIFIED_TEXT}). Everything is still checked "
            "structurally on every save, but if a value looks wrong, "
            "stop and report it.")
